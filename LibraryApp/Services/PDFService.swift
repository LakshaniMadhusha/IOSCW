    @MainActor
    func generateBookingReceipt(user: AppUser, reservation: HallReservation) -> URL? {
        let pdfMetaData = [
            kCGPDFContextCreator: "Library Companion",
            kCGPDFContextAuthor: user.name,
            kCGPDFContextTitle: "Booking Confirmation"
        ]
        let format = UIGraphicsPDFRendererFormat()
        format.documentInfo = pdfMetaData as [String: Any]
        
        let pageWidth = 8.5 * 72.0
        let pageHeight = 11.0 * 72.0
        let pageRect = CGRect(x: 0, y: 0, width: pageWidth, height: pageHeight)
        
        let renderer = UIGraphicsPDFRenderer(bounds: pageRect, format: format)
        let tempURL = FileManager.default.temporaryDirectory.appendingPathComponent("Booking_\(reservation.id.uuidString.prefix(8)).pdf")
        
        do {
            try renderer.writePDF(to: tempURL) { context in
                context.beginPage()
                
                var currentY: CGFloat = 60
                
                // Header
                let titleFont = UIFont.systemFont(ofSize: 24, weight: .bold)
                let headerAttr = [NSAttributedString.Key.font: titleFont, NSAttributedString.Key.foregroundColor: UIColor.systemIndigo]
                "RESERVATION CONFIRMATION".draw(at: CGPoint(x: 60, y: currentY), withAttributes: headerAttr)
                currentY += 40
                
                // Member Info
                let labelFont = UIFont.systemFont(ofSize: 12, weight: .bold)
                let valueFont = UIFont.systemFont(ofSize: 14, weight: .regular)
                
                "MEMBER:".draw(at: CGPoint(x: 60, y: currentY), withAttributes: [NSAttributedString.Key.font: labelFont])
                user.name.draw(at: CGPoint(x: 150, y: currentY), withAttributes: [NSAttributedString.Key.font: valueFont])
                currentY += 25
                
                "DATE:".draw(at: CGPoint(x: 60, y: currentY), withAttributes: [NSAttributedString.Key.font: labelFont])
                reservation.bookingDate.formatted(date: .long, time: .shortened).draw(at: CGPoint(x: 150, y: currentY), withAttributes: [NSAttributedString.Key.font: valueFont])
                currentY += 40
                
                // Reservation Details Card
                let cardRect = CGRect(x: 60, y: currentY, width: pageWidth - 120, height: 180)
                let cardPath = UIBezierPath(roundedRect: cardRect, cornerRadius: 12)
                UIColor.systemGray6.setFill()
                cardPath.fill()
                
                var cardY = currentY + 20
                "HALL/LIBRARY:".draw(at: CGPoint(x: 80, y: cardY), withAttributes: [NSAttributedString.Key.font: labelFont])
                reservation.hallName.draw(at: CGPoint(x: 200, y: cardY), withAttributes: [NSAttributedString.Key.font: valueFont])
                cardY += 25
                
                "ADDRESS:".draw(at: CGPoint(x: 80, y: cardY), withAttributes: [NSAttributedString.Key.font: labelFont])
                reservation.hallAddress.draw(at: CGPoint(x: 200, y: cardY), withAttributes: [NSAttributedString.Key.font: valueFont])
                cardY += 25
                
                "TYPE:".draw(at: CGPoint(x: 80, y: cardY), withAttributes: [NSAttributedString.Key.font: labelFont])
                reservation.reservationType.rawValue.capitalized.draw(at: CGPoint(x: 200, y: cardY), withAttributes: [NSAttributedString.Key.font: valueFont])
                cardY += 25
                
                "DETAILS:".draw(at: CGPoint(x: 80, y: cardY), withAttributes: [NSAttributedString.Key.font: labelFont])
                reservation.reservationDetails.draw(at: CGPoint(x: 200, y: cardY), withAttributes: [NSAttributedString.Key.font: valueFont])
                cardY += 25
                
                "ATTENDEES:".draw(at: CGPoint(x: 80, y: cardY), withAttributes: [NSAttributedString.Key.font: labelFont])
                "\(reservation.attendeeCount)".draw(at: CGPoint(x: 200, y: cardY), withAttributes: [NSAttributedString.Key.font: valueFont])
                
                currentY += 220
                
                // QR Code Note
                "SECURITY VERIFICATION".draw(at: CGPoint(x: 60, y: currentY), withAttributes: [NSAttributedString.Key.font: labelFont, NSAttributedString.Key.foregroundColor: UIColor.systemIndigo])
                currentY += 20
                "Please present the QR code displayed in the app for access. This document serves as a receipt and proof of booking.".draw(in: CGRect(x: 60, y: currentY, width: pageWidth - 120, height: 40), withAttributes: [NSAttributedString.Key.font: valueFont])
                
                // Footer
                let footerFont = UIFont.systemFont(ofSize: 10, weight: .light)
                "Booking ID: \(reservation.id.uuidString)".draw(at: CGPoint(x: 60, y: pageHeight - 80), withAttributes: [NSAttributedString.Key.font: footerFont])
            }
            return tempURL
        } catch {
            return nil
        }

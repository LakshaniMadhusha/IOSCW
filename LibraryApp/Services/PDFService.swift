    @MainActor
    func generateReadingSummary(user: AppUser, sessions: [ReadingSession]) -> URL? {
        let pdfMetaData = [
            kCGPDFContextCreator: "Library Companion",
            kCGPDFContextAuthor: user.name,
            kCGPDFContextTitle: "Reading Summary Report"
        ]
        let format = UIGraphicsPDFRendererFormat()
        format.documentInfo = pdfMetaData as [String: Any]
        
        let pageWidth = 8.5 * 72.0
        let pageHeight = 11 * 72.0
        let pageRect = CGRect(x: 0, y: 0, width: pageWidth, height: pageHeight)
        
        let renderer = UIGraphicsPDFRenderer(bounds: pageRect, format: format)
        
        let tempURL = FileManager.default.temporaryDirectory.appendingPathComponent("ReadingSummary_\(user.name).pdf")
        
        do {
            try renderer.writePDF(to: tempURL) { context in
                context.beginPage()
                
                var currentY: CGFloat = 40
                
                // 1. Header
                let titleFont = UIFont.systemFont(ofSize: 24, weight: .bold)
                let titleAttr = [NSAttributedString.Key.font: titleFont]
                "Reading Journey Summary".draw(at: CGPoint(x: 40, y: currentY), withAttributes: titleAttr)
                currentY += 40
                
                // 2. User Info
                let bodyFont = UIFont.systemFont(ofSize: 14, weight: .regular)
                let boldFont = UIFont.systemFont(ofSize: 14, weight: .bold)
                
                let userText = "Member: \(user.name)"
                userText.draw(at: CGPoint(x: 40, y: currentY), withAttributes: [NSAttributedString.Key.font: boldFont])
                currentY += 20
                
                let dateText = "Generated on: \(Date().formatted(date: .long, time: .shortened))"
                dateText.draw(at: CGPoint(x: 40, y: currentY), withAttributes: [NSAttributedString.Key.font: bodyFont])
                currentY += 40
                
                // 3. Stats
                let totalPoints = sessions.reduce(0) { $0 + ($1.minutes / 10) + $1.challengeBonus }
                let totalMins = sessions.reduce(0) { $0 + $1.minutes }
                
                let statsText = "Total Points: \(totalPoints)  |  Total Reading Time: \(totalMins) minutes"
                statsText.draw(at: CGPoint(x: 40, y: currentY), withAttributes: [NSAttributedString.Key.font: boldFont])
                currentY += 40
                
                // 4. Table Header
                "Date".draw(at: CGPoint(x: 40, y: currentY), withAttributes: [NSAttributedString.Key.font: boldFont])
                "Book Title".draw(at: CGPoint(x: 140, y: currentY), withAttributes: [NSAttributedString.Key.font: boldFont])
                "Minutes".draw(at: CGPoint(x: 400, y: currentY), withAttributes: [NSAttributedString.Key.font: boldFont])
                "Points".draw(at: CGPoint(x: 500, y: currentY), withAttributes: [NSAttributedString.Key.font: boldFont])
                currentY += 25
                
                // Divider
                context.cgContext.setStrokeColor(UIColor.lightGray.cgColor)
                context.cgContext.setLineWidth(1)
                context.cgContext.move(to: CGPoint(x: 40, y: currentY))
                context.cgContext.addLine(to: CGPoint(x: 550, y: currentY))
                context.cgContext.strokePath()
                currentY += 15
                
                // 5. Session Rows
                for session in sessions.prefix(20) { // Limit to top 20 for one page sample
                    if currentY > pageHeight - 60 {
                        context.beginPage()
                        currentY = 40
                    }
                    
                    let dateStr = session.startedAt.formatted(date: .numeric, time: .omitted)
                    let bookTitle = session.book?.title ?? "Activity"
                    let mins = "\(session.minutes)"
                    let pts = "+\((session.minutes / 10) + session.challengeBonus)"
                    
                    dateStr.draw(at: CGPoint(x: 40, y: currentY), withAttributes: [NSAttributedString.Key.font: bodyFont])
                    bookTitle.draw(in: CGRect(x: 140, y: currentY, width: 250, height: 20), withAttributes: [NSAttributedString.Key.font: bodyFont])
                    mins.draw(at: CGPoint(x: 400, y: currentY), withAttributes: [NSAttributedString.Key.font: bodyFont])
                    pts.draw(at: CGPoint(x: 500, y: currentY), withAttributes: [NSAttributedString.Key.font: bodyFont])
                    
                    currentY += 25
                }
                
                // Footer
                let footerText = "Generated by Library Companion App"
                footerText.draw(at: CGPoint(x: pageWidth/2 - 100, y: pageHeight - 40), withAttributes: [NSAttributedString.Key.font: bodyFont, NSAttributedString.Key.foregroundColor: UIColor.lightGray])
            }
            return tempURL
        } catch {
            print("Could not create PDF: \(error)")
            return nil
        }
    }

